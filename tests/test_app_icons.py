"""One icon everywhere: the in-app mark (app.js `mark()`), the favicon, the home-screen icon and the Android icons all come from quantdesk/web/static/app/icon.svg
(PNGs regenerated by deploy/make_icons.mjs), and the links carry a version so a phone that cached an older icon fetches the new one."""
import json
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "quantdesk" / "web" / "static" / "app"


def test_the_in_app_mark_is_drawn_from_the_same_geometry_as_the_icon_file():
    svg = (APP / "icon.svg").read_text()
    js = (APP / "app.js").read_text()
    mark = js[js.index("function mark(size)"):js.index("function buildTabs")]
    for d in re.findall(r'<path d="([^"]+)"', svg):
        assert f'd: "{d}"' in mark, d
    for colour in re.findall(r'(?:fill|stroke)="(#[0-9A-Fa-f]{6})"', svg):
        assert colour in mark, colour
    assert 'rx="15"' in svg and "rx: 15" in mark


def test_the_png_icons_have_their_sizes():
    def size(name):
        return struct.unpack(">II", (APP / name).read_bytes()[16:24])
    assert size("icon-192.png") == (192, 192) and size("icon-512.png") == (512, 512)
    assert size("icon-maskable-512.png") == (512, 512) and size("apple-touch-icon.png") == (180, 180)


def test_every_icon_link_is_versioned_and_points_at_a_real_file():
    html = (APP / "index.html").read_text()
    links = re.findall(r'<link rel="(?:icon|apple-touch-icon|manifest)"[^>]*href="/([^"?]+)\?v=(\d+)"', html)
    assert {f for f, _ in links} == {"manifest.webmanifest", "icon.svg", "icon-192.png", "apple-touch-icon.png"}
    assert all((APP / f).is_file() for f, _ in links) and len({v for _, v in links}) == 1
    man = json.loads((APP / "manifest.webmanifest").read_text())
    for ic in man["icons"]:
        assert re.fullmatch(r"/icon[-\w]*\.png\?v=\d+", ic["src"]) and (APP / ic["src"].lstrip("/").split("?")[0]).is_file()


def test_the_published_site_links_the_icons_relatively_with_the_version(cfg, tmp_path):
    from quantdesk.web.export_site import publish_site
    out = publish_site(cfg, "live", tmp_path / "site")
    html = (out / "index.html").read_text()
    for f in ("manifest.webmanifest", "icon.svg", "icon-192.png", "apple-touch-icon.png"):
        assert f'href="{f}?v=' in html and f'href="/{f}' not in html, f
    man = json.loads((out / "manifest.webmanifest").read_text())
    assert all((out / ic["src"].split("?")[0]).is_file() for ic in man["icons"]) and (out / "icon.svg").is_file()
